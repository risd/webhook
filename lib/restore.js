var fs = require("node:fs")

const errors = require("./errors.js")
var Firebase = require("./util/firebase/index")
var ensureSiteNameAndKeyExist = require("./util/ensure-site-name-and-key-exist")
var getUserLoginInformation = require("./util/get-user-login-information")
var firebaseLoginUser = require("./util/firebase/login-user")

async function Restore(options) {
  var firebase = Firebase(options)

  // Set of basic configuration for this (Defaults)
  var config = {
    cwd: options.cwd || process.cwd(),
    siteName: options.siteName || null,
    siteKey: options.siteKey || null,
    fromFile: options.fromFile || "backup.json",
    firebaseName: options.firebaseName || "webhook",
    firebaseAPIKey: options.firebaseAPIKey,
    firebase: firebase,
    webhookUsername: options.email ? options.email.toLowerCase() : "",
    webhookEscapedUsername: "",
    webhookPassword: options.password,
    platformName: options.platformName || "webhook",
  }

  if (!fs.existsSync(config.fromFile)) {
    var errorMessage = [
      "No webhook back data found.",
      "This command must be run from inside of a webhook site directory",
      "The directory must have a " + config.fromFile + "  file.",
      "`backup.json` can be generated by running `wh backup`.",
    ].join("\n")
    const error = new Error(errorMessage)
    error.code = errors.ERROR_RESTORE_FROM_FILE_NOT_FOUND
    throw new Error(errorMessage)
  }

  await ensureSiteNameAndKeyExist(config)

  if (config.webhookUsername && config.webhookPassword) {
    config.webhookEscapedUsername = escape(config.webhookUsername)
  } else {
    const { username, password } = await getUserLoginInformation(config)
    config.webhookUsername = username
    config.webhookEscapedUsername = escape(config.webhookUsername)
    config.webhookPassword = password
  }

  if (!firebase.currentUser()) {
    await firebaseLoginUser({
      firebase,
      userEmail: config.webhookUsername,
      userPassword: config.webhookPassword,
    })
  }

  const updated = {}

  const siteData = readJson(config.fromFile)
  if (siteData && siteData.data) {
    await firebase.siteData(config, siteData.data)
    updated.data = true
  }
  if (siteData && siteData.contentType) {
    await firebase.siteContentTypes(config, siteData.contentType)
    updated.contentType = true
  }
  if (siteData && siteData.settings) {
    await firebase.siteSettings(config, siteData.settings)
    updated.settings = true
  }
  if (siteData && siteData.deploys) {
    await firebase.siteDeploys(config, siteData.deploys)
    updated.deploys = true
  }

  return { updated }
}

function readJson(path) {
  return JSON.parse(stripBom(fs.readFileSync(path)))
}

function stripBom(content) {
  // we do this because JSON.parse would convert it to a utf8 string if encoding wasn't specified
  if (Buffer.isBuffer(content)) content = content.toString("utf8")
  content = content.replace(/^\uFEFF/, "")
  return content
}

Restore.cliLogSuccess = ({ updated, fromFile }) => {
  const updatedTextPossibilities = {
    data: "Data",
    contentType: "Content Types",
    settings: "Settings",
    deploys: "Deploys",
  }
  const updatedTextArray = []
  Object.keys(updated).forEach((updatedKey) => {
    if (updated[updatedKey] && updatedTextPossibilities[updatedKey]) {
      updatedTextArray.push(updatedTextPossibilities[updatedKey])
    }
  })
  const updatedText = updatedTextArray.join(", ")
  console.log(`Restored ${updatedText} from ${fromFile}.`)
}
Restore.cliLogError = (error, { fromFile }) => {
  console.log(`Error restoring from ${fromFile}.`)
  console.log(error)
}

module.exports = Restore
